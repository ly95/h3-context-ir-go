package service

import (
	"encoding/json"
	"fmt"
	"reflect"
	"regexp"
	"strings"
	"testing"

	"github.com/ly95/contextir/compiler"
)

// Native v3 and native regeneration command are actual public values. The source
// v2/Python-command expectations remain in the original report, not forged here.
func TestRemainingSurfaceGeneratedJS(t *testing.T) {
	js := AsJS()
	_, block, ok := strings.Cut(js, "export const CAMERA_MOVES = ")
	if !ok {
		t.Fatal("moves export missing")
	}
	block, _, ok = strings.Cut(block, "export const DIRECTORS = [")
	if !ok {
		t.Fatal("directors export missing")
	}
	quoted := regexp.MustCompile(`"(?:[^"\\]|\\.)*"`).FindAllString(block, -1)
	var moves []string
	for _, value := range quoted {
		var move string
		if e := json.Unmarshal([]byte(value), &move); e != nil {
			t.Fatal(e)
		}
		moves = append(moves, move)
	}
	if !reflect.DeepEqual(moves, compiler.CameraTypes) {
		t.Fatal("generated JS moves disagree with actual compiler", moves)
	}
	for _, line := range []string{fmt.Sprintf("export const MAX_NOTES = %d;", compiler.MaxDirectorNotesChars), fmt.Sprintf("export const CONTRACT_VERSION = %d;", ContractVersion), fmt.Sprintf("export const DIRECTORS_DIGEST = %q;", Digests()["directors"])} {
		if !strings.Contains("\n"+js, "\n"+line+"\n") {
			t.Fatal("exact published export missing", line)
		}
	}
	if ContractVersion != 3 {
		t.Fatal("native schema changes lack actual current version")
	}
	for _, text := range []string{"GENERATED by `contextir contract -js`", "Do not edit", "go run github.com/ly95/contextir/cmd/contextir contract -js"} {
		if !strings.Contains(js, text) {
			t.Fatal("native module cannot be regenerated using actual Go command", text)
		}
	}
	if strings.Contains(js, "h3ir contract") {
		t.Fatal("native generator incorrectly instructs a Python runtime")
	}
}
